#!/usr/bin/env python3
"""Apply the wiki folder structure defined in schema/structure.json.

    uv run .agents/skills/setup-structure/setup_structure.py check
    uv run .agents/skills/setup-structure/setup_structure.py apply [--dry-run]
    uv run .agents/skills/setup-structure/setup_structure.py identity --team "Name" --repo-url URL [--dry-run] [--no-remote]

`check` validates structure.json and shows what to expect from `apply`.
`apply` creates the folder + README per type, generates missing templates,
refreshes the folder lists in AGENTS.md and README.md and creates an empty
wiki/index.md if it has no rows yet. A type with `"renamed_from"` is renamed
with `git mv` (or os.rename). Nothing is ever deleted; existing folders that
are no longer in the config are only reported.

`identity` replaces the placeholders for team name and repo URL throughout the
repo (README, AGENTS.md, skills, wiki pages) and stores them in
schema/structure.json under "team". It also points the git remote `origin` at
the new URL (`git remote set-url`, or `git remote add` if there is no origin
yet); use --no-remote to leave git alone. It skips this skill's own folder, whose
text uses the placeholders as illustration.

Stdlib only. Run from the repo root.
"""
import json
import os
import re
import subprocess
import sys

CONFIG = os.path.join("schema", "structure.json")
WIKI = "wiki"
RESERVED = {"lint", "archive"}          # fixed folders, not a content type
GENERATED = "<!-- generated by setup-structure: feel free to edit, remove this line to prevent overwriting -->"
BASE_FIELDS = ["title", "aliases", "tags", "status", "contributed-by",
               "generated-by", "date-created", "date-updated", "sources"]
BASE_REQUIRED = ["title", "status", "tags", "date-created", "contributed-by"]
KEY_RE = re.compile(r"^[a-z0-9][a-z0-9\-]*$")


def load():
    with open(CONFIG, encoding="utf-8") as fh:
        return json.load(fh)["types"]


def validate(types):
    errs, seen = [], set()
    if not types:
        errs.append("no type defined")
    for t in types:
        k = t.get("key", "")
        if not KEY_RE.match(k):
            errs.append(f"key {k!r}: only lowercase letters, digits and hyphens")
        if k in RESERVED or k in ("index", "log"):
            errs.append(f"key {k!r} is reserved")
        if k in seen:
            errs.append(f"key {k!r} appears more than once")
        seen.add(k)
        if t.get("layout") not in ("folder", "file"):
            errs.append(f"{k}: layout must be 'folder' or 'file'")
        for f in ("label", "label_plural", "description", "naming"):
            if not t.get(f):
                errs.append(f"{k}: field '{f}' is missing")
        if t.get("in_index") and t.get("layout") != "folder":
            errs.append(f"{k}: in_index is only allowed with layout 'folder'")
        tpl = t.get("template")
        if tpl and (os.sep in tpl or not tpl.endswith(".md")):
            errs.append(f"{k}: template must be a .md file name in schema/")
    return errs


def run_git_mv(src, dst):
    try:
        subprocess.run(["git", "mv", src, dst], check=True, capture_output=True)
    except (subprocess.CalledProcessError, FileNotFoundError):
        os.rename(src, dst)


def is_generated(path):
    if not os.path.exists(path):
        return True
    with open(path, encoding="utf-8") as fh:
        return GENERATED in fh.read()


def readme_text(t):
    lines = [GENERATED, "", f"# {t['label_plural']}", "", t["description"], ""]
    lines.append(f"Naming convention: `{t['naming']}`")
    if t["layout"] == "folder":
        lines += ["", f"Each {t['label'].lower()} has its own subfolder with an `index.md`."]
        if t.get("subfolders"):
            lines.append("Additional files go in the same subfolder, for example in: "
                         + ", ".join(f"`{s}/`" for s in t["subfolders"]) + ".")
    if t.get("template"):
        lines += ["", f"Use `schema/{t['template']}` for new pages."]
    lines += ["", "The agent creates pages and subfolders based on approved notes from the local inbox.",
              "Do not create folders here yourself: that disrupts the index.", ""]
    return "\n".join(lines)


def template_text(t):
    path = (f"wiki/{t['key']}/<slug>/index.md" if t["layout"] == "folder"
            else f"wiki/{t['key']}/{t['naming']}")
    extra = t.get("fields", [])
    fm = ["---"]
    for f in BASE_FIELDS:
        if f == "tags":
            fm.append(f"tags: [{t['key']}]")
        elif f == "status":
            fm.append("status: draft")
        elif f in ("aliases", "contributed-by", "sources"):
            fm.append(f"{f}: []")
        else:
            fm.append(f"{f}: ")
        if f == "status":
            for e in extra:
                fm.append(f"{e['name']}: ")
    fm.append("---")
    out = [GENERATED, "", f"# {t['label']} template", "",
           f"Use this template for new pages in `{path}`.",
           f"Naming convention: `{t['naming']}`", "", "---", "",
           "```yaml", *fm, "```", ""]
    if t.get("status_values"):
        out += ["**`status`** — one of: " + " · ".join(f"`{s}`" for s in t["status_values"]) + ".", ""]
    for e in extra:
        out.append(f"**`{e['name']}`** — {e.get('hint', '')}" + (" (required)" if e.get("required") else ""))
        out.append("")
    out += ["---", ""]
    for s in t.get("sections") or ["Summary", "Details", "Open questions", "Related"]:
        out += [f"## {s}", ""]
    return "\n".join(out)


def tree_lines(types):
    out = []
    for t in types:
        pad = f"  wiki/{t['key']}/"
        desc = t.get("short") or t["description"]
        out.append(f"{pad:<35}{desc}")
        if t["layout"] == "folder":
            subs = "  ".join(["index.md"] + [f"{s}/" for s in t.get("subfolders", [])])
            out.append(f"{'':<35}  ({t['naming']}; {subs})")
    return out


def readme_rows(types):
    return [f"| `wiki/{t['key']}/` | {t['description']} |" for t in types]


def replace_region(path, start_re, end_re, new_lines, dry):
    """Replace the lines between the anchors (the anchors stay)."""
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    s = next((i for i, l in enumerate(lines) if re.search(start_re, l)), None)
    e = next((i for i, l in enumerate(lines) if s is not None and i > s and re.search(end_re, l)), None)
    if s is None or e is None:
        return f"{path}: anchors not found ({start_re!r} .. {end_re!r}); adjust the list by hand"
    new = lines[:s + 1] + new_lines + lines[e:]
    if new != lines and not dry:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(new))
    return None


def index_text(types):
    out = ["---", "title: Overview", "status: stub", "generated-by: ", "date-updated: ", "---", "",
           "# Overview", "", "_Updated by agent. Add cases via the local inbox._", "", "---", ""]
    for t in (x for x in types if x.get("in_index")):
        cols = [t["label"]] + t.get("index_columns", []) + ["Status"]
        out += [f"## {t['label_plural']}", "", "| " + " | ".join(cols) + " |",
                "|" + "---|" * len(cols), ""]
    if not any(x.get("in_index") for x in types):
        out += ["_No type with `in_index` in schema/structure.json._", ""]
    return "\n".join(out)


def index_has_rows():
    p = os.path.join(WIKI, "index.md")
    if not os.path.exists(p):
        return False
    with open(p, encoding="utf-8") as fh:
        text = re.sub(r"<!--.*?-->", "", fh.read(), flags=re.DOTALL)
        return bool(re.search(r"^\|\s*\[.+\]\(.+\.md\)", text, re.MULTILINE))


def write(path, text, dry, log):
    log.append(("(dry) " if dry else "") + f"write {path}")
    if not dry:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)


def apply(types, dry):
    log, warn = [], []
    for t in types:                                  # 1. rename
        old = t.get("renamed_from")
        if old:
            src, dst = os.path.join(WIKI, old), os.path.join(WIKI, t["key"])
            if os.path.isdir(src) and not os.path.exists(dst):
                log.append(("(dry) " if dry else "") + f"rename {src} -> {dst}")
                if not dry:
                    run_git_mv(src, dst)
            elif os.path.isdir(src):
                warn.append(f"{src} and {dst} both exist; merge by hand")
    for t in types:                                  # 2. folder + README + template
        d = os.path.join(WIKI, t["key"])
        if not os.path.isdir(d):
            log.append(("(dry) " if dry else "") + f"create {d}/")
            if not dry:
                os.makedirs(d)
        readme = os.path.join(d, "README.md")
        if is_generated(readme):
            write(readme, readme_text(t), dry, log)
        else:
            warn.append(f"{readme} was edited by hand; not overwritten")
        if t.get("template"):
            tp = os.path.join("schema", t["template"])
            if not os.path.exists(tp) or is_generated(tp):
                write(tp, template_text(t), dry, log)
    # AGENTS.md: list sits between log.md and lint/; README.md: between index.md row and log.md row
    for args in (("AGENTS.md", r"^\s*wiki/log\.md\b", r"^\s*wiki/lint/", tree_lines(types)),
                 ("README.md", r"^\| `wiki/index\.md` \|", r"^\| `wiki/log\.md` \|", readme_rows(types))):
        m = replace_region(*args, dry)
        if m:
            warn.append(m)
        else:
            log.append(("(dry) " if dry else "") + f"refresh folder list in {args[0]}")
    ip = os.path.join(WIKI, "index.md")             # 4. index
    if not index_has_rows():
        write(ip, index_text(types), dry, log)
    else:
        warn.append("wiki/index.md already has rows and was not rewritten; check the headings by hand")
    keys = {t["key"] for t in types} | RESERVED     # 5. orphans
    for name in sorted(os.listdir(WIKI)):
        if os.path.isdir(os.path.join(WIKI, name)) and name not in keys:
            warn.append(f"wiki/{name}/ is not in structure.json (not deleted)")
    return log, warn


PLACEHOLDERS = {"team": "<TEAM-NAME>", "repo_url": "<REPO-URL>"}
SKIP_DIRS = {".git", ".venv", "node_modules", "__pycache__"}
SKIP_PREFIX = os.path.join(".agents", "skills", "setup-structure")


def set_remote(repo_url, dry):
    """Point `origin` at repo_url (local git config only; nothing is pushed)."""
    pre = "(dry) " if dry else ""
    try:
        cur = subprocess.run(["git", "remote", "get-url", "origin"], capture_output=True, text=True)
    except FileNotFoundError:
        return [pre + "git not found; remote not changed"]
    if cur.returncode == 0:
        if cur.stdout.strip() == repo_url:
            return [pre + "git remote origin already correct"]
        cmd, msg = ["git", "remote", "set-url", "origin", repo_url], \
            f"git remote set-url origin {repo_url} (was {cur.stdout.strip()})"
    else:
        cmd, msg = ["git", "remote", "add", "origin", repo_url], f"git remote add origin {repo_url}"
    if not dry:
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            return [f"NOTE: {' '.join(cmd)} failed: {r.stderr.strip()}"]
    return [pre + msg]


def identity(team, repo_url, dry):
    """Replace <TEAM-NAME> / <REPO-URL> in all text files; record them in structure.json."""
    values = {PLACEHOLDERS["team"]: team, PLACEHOLDERS["repo_url"]: repo_url}
    log = []
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        if os.path.relpath(root, ".").startswith(SKIP_PREFIX):
            continue
        for name in files:
            path = os.path.join(root, name)
            try:
                with open(path, encoding="utf-8") as fh:
                    text = fh.read()
            except (UnicodeDecodeError, OSError):
                continue
            new = text
            for ph, val in values.items():
                new = new.replace(ph, val)
            if new != text:
                log.append(("(dry) " if dry else "") + f"update {os.path.relpath(path, '.')}")
                if not dry:
                    with open(path, "w", encoding="utf-8") as fh:
                        fh.write(new)
    with open(CONFIG, encoding="utf-8") as fh:
        cfg = json.load(fh)
    cfg["team"] = {"name": team, "repo_url": repo_url}
    log.append(("(dry) " if dry else "") + f"record team in {CONFIG}")
    if not dry:
        with open(CONFIG, "w", encoding="utf-8") as fh:
            json.dump(cfg, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    if "--no-remote" not in sys.argv:
        log += set_remote(repo_url, dry)
    return log


def arg_value(flag):
    if flag in sys.argv:
        i = sys.argv.index(flag)
        if i + 1 < len(sys.argv):
            return sys.argv[i + 1]
    return None


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "identity":
        team, url = arg_value("--team"), arg_value("--repo-url")
        if not team or not url:
            print("error: identity needs --team and --repo-url", file=sys.stderr)
            sys.exit(2)
        if not os.path.exists(CONFIG):
            print("error: run from the repo root", file=sys.stderr)
            sys.exit(1)
        dry = "--dry-run" in sys.argv
        for l in identity(team, url, dry):
            print(" ", l)
        sys.exit(0)
    if len(sys.argv) < 2 or sys.argv[1] not in ("check", "apply"):
        print(__doc__)
        sys.exit(2)
    if not os.path.isdir(WIKI) or not os.path.exists(CONFIG):
        print("error: run from the repo root (expected wiki/ and schema/structure.json)", file=sys.stderr)
        sys.exit(1)
    types = load()
    errs = validate(types)
    if errs:
        print("structure.json is invalid:")
        for e in errs:
            print("  -", e)
        sys.exit(1)
    dry = sys.argv[1] == "check" or "--dry-run" in sys.argv
    log, warn = apply(types, dry)
    print(f"{len(types)} types: " + ", ".join(t["key"] for t in types) + "\n")
    for l in log:
        print(" ", l)
    for w in warn:
        print("  NOTE:", w)
    if dry:
        print("\n(nothing written; run `apply` to carry it out)")


if __name__ == "__main__":
    main()
